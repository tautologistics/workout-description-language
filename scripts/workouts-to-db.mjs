#!/usr/bin/env node
/**
 * Ingest the authored `.wdl` library under `examples/workouts/<org>/<slug>.wdl`
 * into the PocketBase `workouts` collection over `/api` — queue task L6,
 * DEC-021. The curated public benchmark sets (`crossfit` / `hyrox` / `tabata`,
 * authored in L5) move into the DB; this script is how they get there, and how
 * a dev re-seeds a local mock or a fresh box. It is the twin of
 * `scripts/movements-to-db.mjs` (`make movements:load`) for `workouts`.
 *
 * **Idempotent, keyed by `wdlId`** (`<orghandle>:<slug>`). Every file is looked
 * up by its `wdlId`; absent → `POST`, present → `PATCH` only when `title` /
 * `source` / `visibility` / `owner` actually differ. A second run writes
 * nothing (reported as all-`unchanged`). `--dry-run` reports the planned
 * POSTs/PATCHes and writes nothing at all (no HTTP mutation, no fixture
 * rewrite).
 *
 * **Field mapping** — one `workouts` row per file:
 *   - `owner` = the org `users` row's fixed id for the file's directory
 *     (`crossfit`→`org0crossfit001`, `hyrox`→`org0hyrox000001`,
 *     `tabata`→`org0tabata00001`; the ids the L1 migration
 *     `1756900000_add_users_handle_and_orgs.js` inserts).
 *   - `wdlId` / the `@id` line = `<orghandle>:<slug>`, forced the same way
 *     `apps/shared/pocketbase.js` forces it on an interactive save (DEC-021):
 *     `<slug>` is the slug portion of the file's own `@id` (else the `# Title`,
 *     else `untitled`), and the `@id` directive line in `source` is rewritten
 *     to match. The authored files are already canonical, so this is a no-op on
 *     them — it is here so a hand-edited or half-canonical file still lands
 *     namespaced. No same-owner suffix logic: each authored `@id` is distinct.
 *   - `title` = the `# Title` line; `source` = the file body (with the `@id`
 *     line forced as above); `visibility` = `"public"`.
 *
 * **The same run regenerates the committed fixtures** (unless `--dry-run`):
 *   - `fixtures/workouts.json` — the 43 library rows (deterministic 15-char
 *     ids derived from `wdlId`), plus every pre-existing row that is *not*
 *     owned by an org (the mock signed-in user's own seed workouts, which
 *     exercise the builder's *My workouts* list from a fresh `make serve`).
 *     The old hand-added `crossfit:helen` row (owned by the `crossfit` org) is
 *     replaced by the generated one — same `wdlId`.
 *   - `fixtures/users.json` — the three `org: true` rows (same fixed ids /
 *     handles the L1 migration commits), plus the mock signed-in user row
 *     (kept exactly as found — committed with no `handle` on purpose, task L1).
 *   Each file is only rewritten when its content actually changes, so a re-run
 *   with nothing new leaves `git status` clean. `registry/movements.json`
 *   being its own committed fixture (regenerated by `movements-from-db.mjs`) is
 *   the precedent.
 *
 * **Target** — `--api <base>` or `WDL_PB_URL`, default `http://localhost:8081`
 * (matches `make serve`). Against the mock (`make serve`) writes need no auth.
 * Against a real PocketBase, writes need admin auth — the `workouts` write rule
 * is owner-only, so this must be a **superuser** token/login (a plain
 * `admin: true` `users` row is not the org owner and will be rejected):
 *   - `WDL_PB_ADMIN_TOKEN` — a token, used as-is; or
 *   - `WDL_PB_ADMIN_EMAIL` + `WDL_PB_ADMIN_PASSWORD` — exchanged at
 *     `POST /api/collections/<c>/auth-with-password` where `<c>` is
 *     `WDL_PB_ADMIN_COLLECTION` (default `_superusers` here, unlike
 *     `movements:load` whose movements rule is satisfied by a `users` admin).
 *   - Neither set → the dev-mock OAuth stub is tried (`make serve` accepts it);
 *     against a real PocketBase that fails and the script says what to set.
 * The token rides as the `Authorization` header on every write.
 *
 * The authored `.wdl` files, `packages/core`, the grammar and the spec are
 * untouched: this script only reads `examples/workouts/`, talks to `/api`, and
 * rewrites the two `fixtures/*.json` files.
 *
 *   node scripts/workouts-to-db.mjs [--api <base>] [--dry-run]
 *   make workouts:load                 # same, WDL_PB_URL to point elsewhere
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

/** Directory name under examples/workouts/ -> the org `users` row's fixed id. */
const ORG_IDS = {
  crossfit: 'org0crossfit001',
  hyrox: 'org0hyrox000001',
  tabata: 'org0tabata00001',
};

const LIB_DIR = 'examples/workouts';
const CMP_FIELDS = ['title', 'source', 'visibility', 'owner'];
const FIXTURE_TS = '2026-09-01 00:00:00.000Z';

const args = process.argv.slice(2);
const flag = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? (args[i + 1] ?? '') : undefined;
};
const DRY_RUN = args.includes('--dry-run');
const BASE = (flag('--api') ?? process.env.WDL_PB_URL ?? 'http://localhost:8081').replace(/\/+$/, '');
const COLL = `${BASE}/api/collections/workouts/records`;

async function main() {
  const rows = readLibrary();
  if (!rows.length) throw new Error(`no .wdl files under ${LIB_DIR}/`);
  console.log(`workouts:load: ${rows.length} file(s) -> ${BASE}${DRY_RUN ? '  (dry run — no writes)' : ''}`);

  const token = await authenticate();
  const existing = await fetchExisting(token);
  console.log(`  ${existing.size} row(s) already in the collection`);

  const tally = { created: 0, updated: 0, unchanged: 0 };
  for (const row of rows) {
    const have = existing.get(row.wdlId);
    if (!have) {
      if (!DRY_RUN) await send('POST', COLL, token, createBody(row));
      tally.created++;
      log('POST  ', row.wdlId);
    } else {
      const patch = diff(row, have);
      if (Object.keys(patch).length === 0) {
        tally.unchanged++;
      } else {
        if (!DRY_RUN) await send('PATCH', `${COLL}/${encodeURIComponent(have.id)}`, token, patch);
        tally.updated++;
        log('PATCH ', row.wdlId, `(${Object.keys(patch).join(', ')})`);
      }
    }
  }

  console.log(
    `\n${DRY_RUN ? 'would be: ' : 'done: '}` +
    `${tally.created} created, ${tally.updated} updated, ${tally.unchanged} unchanged`,
  );
  if (!DRY_RUN && tally.created === 0 && tally.updated === 0) {
    console.log(`  (nothing changed — the collection already matches ${LIB_DIR}/)`);
  }

  if (DRY_RUN) {
    console.log('  (dry run — fixtures/workouts.json and fixtures/users.json not rewritten)');
    return;
  }
  regenerateFixtures(rows);
}

const log = (verb, id, extra = '') => {
  if (DRY_RUN || process.env.WDL_VERBOSE) console.log(`  ${verb} ${id}${extra ? '  ' + extra : ''}`);
};

// --- read the authored library ------------------------------------------------

/** Every `examples/workouts/<org>/<slug>.wdl`, as a desired `workouts` row. */
function readLibrary() {
  const root = join(process.cwd(), LIB_DIR);
  const out = [];
  for (const org of readdirSync(root, { withFileTypes: true })) {
    if (!org.isDirectory()) continue;
    const owner = ORG_IDS[org.name];
    if (!owner) throw new Error(`${LIB_DIR}/${org.name}/ has no known org id (expected one of ${Object.keys(ORG_IDS).join(', ')})`);
    const handle = org.name;
    for (const f of readdirSync(join(root, org.name), { withFileTypes: true })) {
      if (!f.isFile() || !f.name.endsWith('.wdl')) continue;
      const body = readFileSync(join(root, org.name, f.name), 'utf8');
      const slug = slugOfIdValue(readIdValue(body)) || slugify(readTitleLine(body)) || 'untitled';
      const wdlId = `${handle}:${slug}`;
      out.push({
        wdlId,
        owner,
        title: readTitleLine(body) || slug,
        source: writeIdLine(body, wdlId),
        visibility: 'public',
      });
    }
  }
  out.sort((a, b) => (a.wdlId < b.wdlId ? -1 : a.wdlId > b.wdlId ? 1 : 0));
  const seen = new Set();
  for (const r of out) {
    if (seen.has(r.wdlId)) throw new Error(`two files resolve to the same wdlId: ${r.wdlId}`);
    seen.add(r.wdlId);
  }
  return out;
}

// --- @id / slug helper (a port of apps/shared/pocketbase.js's block) ---------
// `@id`'s value is uninterpreted by the grammar (spec §2), so a light regex on
// the zero-indent preamble line is all this needs — no `packages/core` import.

const slugify = (s) => String(s ?? '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
const readIdValue = (src) => (String(src ?? '').match(/^@id[ \t]+(\S.*?)[ \t]*$/m) || [, ''])[1];
const readTitleLine = (src) => (String(src ?? '').match(/^#[ \t]+(\S.*?)[ \t]*$/m) || [, ''])[1];
const slugOfIdValue = (v) => (v ? slugify(v.includes(':') ? v.slice(v.indexOf(':') + 1) : v) : '');

/** Write (or rewrite) the zero-indent `@id` line of `source` to `id`. */
function writeIdLine(source, id) {
  const lines = String(source ?? '').split('\n');
  const at = lines.findIndex((l) => /^@id(?:\s|$)/.test(l));
  if (at !== -1) { lines[at] = `@id ${id}`; return lines.join('\n'); }
  let ins = 0;
  for (let i = 0; i < lines.length; i++) {
    const t = lines[i].trim();
    if ((t === '' || t.startsWith('//')) && i === ins) { ins = i + 1; continue; }
    if (t.startsWith('#') || /^@[A-Za-z][\w-]*(?:\s|$)/.test(t)) { ins = i + 1; continue; }
    break;
  }
  const chunk = [`@id ${id}`];
  if (lines[ins] !== undefined && lines[ins].trim() !== '') chunk.push('');
  lines.splice(ins, 0, ...chunk);
  return lines.join('\n');
}

// --- auth (mirrors scripts/movements-to-db.mjs) -----------------------------

async function authenticate() {
  if (process.env.WDL_PB_ADMIN_TOKEN) {
    return process.env.WDL_PB_ADMIN_TOKEN;
  }
  const email = process.env.WDL_PB_ADMIN_EMAIL;
  const password = process.env.WDL_PB_ADMIN_PASSWORD;
  if (email && password) {
    const coll = process.env.WDL_PB_ADMIN_COLLECTION || '_superusers';
    const out = await send('POST', `${BASE}/api/collections/${coll}/auth-with-password`, null, {
      identity: email,
      password,
    });
    if (!out?.token) throw new Error(`auth-with-password against '${coll}' returned no token`);
    console.log(`  authed as ${email} (collection '${coll}')`);
    return out.token;
  }
  // No explicit credentials. `make serve`'s mock accepts a stubbed OAuth
  // exchange and does not gate `workouts` writes at all; a real PocketBase
  // rejects both, and the catch below says what to set.
  try {
    const out = await send('POST', `${BASE}/api/collections/users/auth-with-oauth2`, null, {
      provider: 'google',
      code: 'workouts-load',
      codeVerifier: 'workouts-load',
      redirectURL: `${BASE}/`,
    });
    if (!out?.token) throw new Error('no token');
    console.log('  authed via the dev mock (no WDL_PB_ADMIN_* set)');
    return out.token;
  } catch {
    throw new Error(
      'writing to a real PocketBase needs superuser auth (the workouts write rule is owner-only).\n' +
      '  set WDL_PB_ADMIN_TOKEN, or WDL_PB_ADMIN_EMAIL + WDL_PB_ADMIN_PASSWORD\n' +
      "  (WDL_PB_ADMIN_COLLECTION defaults to '_superusers' here).\n" +
      `  target: ${BASE}  (override with --api <base> or WDL_PB_URL)`,
    );
  }
}

// --- fetch existing --------------------------------------------------------

/** Every row already in the collection, as a Map keyed by `wdlId` (blank skipped). */
async function fetchExisting(token) {
  const map = new Map();
  let page = 1;
  for (;;) {
    const url = `${COLL}?perPage=500&page=${page}&sort=wdlId`;
    const env = await send('GET', url, token);
    for (const rec of env.items ?? []) if (rec.wdlId) map.set(rec.wdlId, rec);
    if (!env.totalPages || page >= env.totalPages) break;
    page++;
  }
  return map;
}

// --- field mapping -------------------------------------------------------

function createBody(row) {
  return {
    owner: row.owner,
    title: row.title,
    source: row.source,
    wdlId: row.wdlId,
    visibility: row.visibility,
  };
}

/** Fields where the file and the row disagree — the PATCH body (may be {}). */
function diff(row, rec) {
  const patch = {};
  for (const k of CMP_FIELDS) {
    if (String(row[k] ?? '') !== String(rec[k] ?? '')) patch[k] = row[k];
  }
  return patch;
}

// --- fixture regeneration ------------------------------------------------

function regenerateFixtures(rows) {
  rewriteWorkoutsFixture(rows);
  rewriteUsersFixture();
}

const P = (...p) => join(process.cwd(), ...p);

/** Rewrite `fixtures/workouts.json` iff its content changes. */
function rewriteWorkoutsFixture(rows) {
  const path = P('fixtures/workouts.json');
  const current = readJson(path);
  const kept = (current.workouts ?? []).filter(
    (w) => !Object.values(ORG_IDS).includes(w.owner),
  );
  const library = rows.map((r) => ({
    id: fixtureId(r.wdlId),
    collectionId: 'mock_workouts',
    collectionName: 'workouts',
    owner: r.owner,
    title: r.title,
    source: r.source,
    wdlId: r.wdlId,
    visibility: r.visibility,
    created: FIXTURE_TS,
    updated: FIXTURE_TS,
  }));
  const next = {
    $comment: 'Seed rows for the local dev mock /api `workouts` collection (scripts/mock-api.mjs). The library rows (owner = an org row, visibility:public, wdlId set) are regenerated from examples/workouts/**/*.wdl by `make workouts:load` (scripts/workouts-to-db.mjs) — do not hand-edit them; edit the .wdl file and re-run. Rows owned by a non-org user (the mock signed-in user, users[0] in fixtures/users.json) are hand-kept seed data for the builder’s My workouts list and are preserved across regenerations. Runtime create/update/delete land in fixtures/workouts.local.json (git-ignored); delete it to reset. Shape follows deploy/pocketbase/pb_migrations/1756600000_create_workouts.js.',
    workouts: [...kept, ...library],
  };
  writeJsonIfChanged(path, next, 'fixtures/workouts.json');
}

/** Rewrite `fixtures/users.json` iff its content changes. */
function rewriteUsersFixture() {
  const path = P('fixtures/users.json');
  const current = readJson(path);
  const users = current.users ?? [];
  const nonOrg = users.filter((u) => !Object.values(ORG_IDS).includes(u.id));
  const orgRows = [
    ['org0crossfit001', 'crossfit'],
    ['org0hyrox000001', 'hyrox'],
    ['org0tabata00001', 'tabata'],
  ].map(([id, handle]) => {
    const prev = users.find((u) => u.id === id) ?? {};
    return {
      id,
      collectionId: '_pb_users_auth_',
      collectionName: 'users',
      email: `${handle}@orgs.wdl.invalid`,
      emailVisibility: false,
      verified: true,
      name: handle,
      avatar: '',
      admin: false,
      org: true,
      handle,
      created: prev.created ?? FIXTURE_TS,
      updated: prev.updated ?? FIXTURE_TS,
    };
  });
  const next = { $comment: current.$comment, users: [...nonOrg, ...orgRows] };
  if (!next.$comment) delete next.$comment;
  writeJsonIfChanged(path, next, 'fixtures/users.json');
}

/** A deterministic 15-char PocketBase-shaped record id for a library row. */
function fixtureId(wdlId) {
  let h = 5381;
  for (let i = 0; i < wdlId.length; i++) h = ((h << 5) + h + wdlId.charCodeAt(i)) >>> 0;
  return ('wk' + h.toString(36).padStart(13, '0')).slice(0, 15);
}

function readJson(p) {
  try { return JSON.parse(readFileSync(p, 'utf8')); }
  catch { return {}; }
}

function writeJsonIfChanged(path, obj, label) {
  const text = JSON.stringify(obj, null, 2) + '\n';
  let prev = '';
  try { prev = readFileSync(path, 'utf8'); } catch { /* new file */ }
  if (prev === text) {
    console.log(`  ${label}: unchanged`);
    return;
  }
  writeFileSync(path, text);
  console.log(`  ${label}: rewritten`);
}

// --- transport (mirrors scripts/movements-to-db.mjs) --------------------

async function send(method, url, token, body) {
  const headers = {};
  if (body !== undefined) headers['Content-Type'] = 'application/json';
  if (token) headers.Authorization = token;
  const res = await fetch(url, {
    method,
    headers,
    body: body !== undefined ? JSON.stringify(body) : undefined,
  });
  if (res.status === 204) return null;
  const data = await res.json().catch(() => ({}));
  if (!res.ok) {
    const detail = data?.data && Object.keys(data.data).length ? ` ${JSON.stringify(data.data)}` : '';
    const err = new Error(`${method} ${url.replace(BASE, '')} — ${res.status} ${data?.message || res.statusText}${detail}`);
    err.status = res.status;
    throw err;
  }
  return data;
}

// --- entry point ---------------------------------------------------------

main().catch((e) => {
  console.error(`\nworkouts:load: ${e.message}`);
  process.exit(1);
});
